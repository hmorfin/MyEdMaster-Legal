from django.db import models


LEVEL_CHOICES = [
    ("beginner",     "Beginner"),
    ("intermediate", "Intermediate"),
    ("advanced",     "Advanced"),
]

SCOPE_CHOICES = [
    ("lesson", "Lesson"),
    ("module", "Module"),
    ("course", "Course"),
]

STATUS_CHOICES = [
    ("in_progress", "In Progress"),
    ("completed",   "Completed"),
]


# ── Course Catalog ────────────────────────────────────────────────────────

class Course(models.Model):
    """
    Top-level course. Each legal topic has three courses (one per level).
    Lesson content is LLM-generated on first access and cached in Lesson.content.
    """
    legal_topic   = models.CharField(max_length=100)          # e.g. "Tenant & Landlord Rights"
    level         = models.CharField(max_length=20, choices=LEVEL_CHOICES)
    title         = models.CharField(max_length=255)
    description   = models.TextField()
    pass_threshold = models.FloatField(default=0.70)          # min score to unlock next level
    order         = models.PositiveIntegerField(default=0)    # display order within topic
    created_at    = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ("legal_topic", "level")
        ordering = ["legal_topic", "order"]

    def __str__(self):
        return f"{self.legal_topic} — {self.get_level_display()}"


class Module(models.Model):
    course  = models.ForeignKey(Course, on_delete=models.CASCADE, related_name="modules")
    title   = models.CharField(max_length=255)
    order   = models.PositiveIntegerField(default=0)

    class Meta:
        ordering = ["order"]

    def __str__(self):
        return f"{self.course} / {self.title}"


class Lesson(models.Model):
    """
    Lesson content is generated by the LLM on first access and cached here.
    learning_objectives is a JSON list of strings.
    """
    module               = models.ForeignKey(Module, on_delete=models.CASCADE, related_name="lessons")
    title                = models.CharField(max_length=255)
    order                = models.PositiveIntegerField(default=0)
    learning_objectives  = models.JSONField(default=list)
    content              = models.TextField(blank=True)        # LLM-generated markdown, cached
    content_generated_at = models.DateTimeField(null=True, blank=True)
    created_at           = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["order"]

    def __str__(self):
        return f"{self.module} / {self.title}"


# ── Enrollment & Progress ─────────────────────────────────────────────────

class Enrollment(models.Model):
    user        = models.ForeignKey("users.UserProfile", on_delete=models.CASCADE, related_name="enrollments")
    course      = models.ForeignKey(Course, on_delete=models.CASCADE, related_name="enrollments")
    status      = models.CharField(max_length=20, choices=STATUS_CHOICES, default="in_progress")
    enrolled_at = models.DateTimeField(auto_now_add=True)
    completed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        unique_together = ("user", "course")

    def __str__(self):
        return f"{self.user} enrolled in {self.course}"


class LessonProgress(models.Model):
    user         = models.ForeignKey("users.UserProfile", on_delete=models.CASCADE, related_name="lesson_progress")
    lesson       = models.ForeignKey(Lesson, on_delete=models.CASCADE, related_name="progress")
    completed    = models.BooleanField(default=False)
    completed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        unique_together = ("user", "lesson")


# ── Assessment ────────────────────────────────────────────────────────────

class Assessment(models.Model):
    """
    One assessment per user per lesson/module/course attempt.
    questions stores the full MCQ list including correct answers and explanations.
    user_answers maps question index → chosen option index.
    """
    user         = models.ForeignKey("users.UserProfile", on_delete=models.CASCADE, related_name="assessments")
    lesson       = models.ForeignKey(Lesson,  on_delete=models.SET_NULL, null=True, blank=True, related_name="assessments")
    module       = models.ForeignKey(Module,  on_delete=models.SET_NULL, null=True, blank=True, related_name="assessments")
    course       = models.ForeignKey(Course,  on_delete=models.SET_NULL, null=True, blank=True, related_name="assessments")
    scope        = models.CharField(max_length=10, choices=SCOPE_CHOICES)

    # LLM-generated questions stored as JSON list
    questions    = models.JSONField(default=list)
    # {question_index: chosen_option_index}
    user_answers = models.JSONField(default=dict)

    score        = models.FloatField(null=True, blank=True)   # 0.0 – 1.0
    passed       = models.BooleanField(null=True, blank=True)
    feedback     = models.TextField(blank=True)               # LLM-generated overall feedback
    next_action  = models.CharField(max_length=50, blank=True)  # retry | next_lesson | next_module | unlock_next_level

    created_at   = models.DateTimeField(auto_now_add=True)
    submitted_at = models.DateTimeField(null=True, blank=True)

    def __str__(self):
        return f"{self.user} — {self.scope} assessment (score={self.score})"