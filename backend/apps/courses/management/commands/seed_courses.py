class Command(BaseCommand):
    help = "Seed the course catalog with predefined legal courses, modules, and lessons."

    def handle(self, *args, **kwargs):
        created_courses = 0
        created_modules = 0
        created_lessons = 0

        for topic_data in CATALOG:
            topic = topic_data["legal_topic"]
            for level_index, level_data in enumerate(topic_data["levels"]):
                course, course_created = Course.objects.get_or_create(
                    legal_topic=topic,
                    level=level_data["level"],
                    defaults={
                        "title":          level_data["title"],
                        "description":    level_data["description"],
                        "pass_threshold": level_data["pass_threshold"],
                        "order":          level_index,
                    }
                )
                if course_created:
                    created_courses += 1
                    self.stdout.write(f"  Created course: {course}")

                for mod_index, mod_data in enumerate(level_data["modules"]):
                    module, mod_created = Module.objects.get_or_create(
                        course=course,
                        title=mod_data["title"],
                        defaults={"order": mod_index}
                    )
                    if mod_created:
                        created_modules += 1

                    for lesson_index, (lesson_title, objectives) in enumerate(mod_data["lessons"]):
                        lesson, lesson_created = Lesson.objects.get_or_create(
                            module=module,
                            title=lesson_title,
                            defaults={
                                "order":               lesson_index,
                                "learning_objectives": objectives,
                            }
                        )
                        if lesson_created:
                            created_lessons += 1

        self.stdout.write(self.style.SUCCESS(
            f"\nSeeding complete: {created_courses} courses, "
            f"{created_modules} modules, {created_lessons} lessons created."
        ))